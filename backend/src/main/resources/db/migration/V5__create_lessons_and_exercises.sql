ALTER TABLE grammar_concepts
    ADD COLUMN has_lesson BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE grammar_lessons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_id BIGINT NOT NULL UNIQUE REFERENCES grammar_concepts(id) ON DELETE CASCADE,
    explanation TEXT NOT NULL
);

CREATE TABLE grammar_examples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES grammar_lessons(id) ON DELETE CASCADE,
    english_text VARCHAR(500) NOT NULL,
    turkish_translation VARCHAR(500) NOT NULL,
    order_index INTEGER NOT NULL,
    UNIQUE (lesson_id, order_index)
);

CREATE TABLE grammar_exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_id BIGINT NOT NULL REFERENCES grammar_concepts(id) ON DELETE CASCADE,
    exercise_type VARCHAR(32) NOT NULL,
    prompt VARCHAR(500) NOT NULL,
    options_json JSONB NOT NULL,
    correct_answer VARCHAR(300) NOT NULL,
    explanation TEXT NOT NULL,
    order_index INTEGER NOT NULL,
    UNIQUE (concept_id, order_index)
);

CREATE TABLE grammar_concept_prerequisites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_id BIGINT NOT NULL REFERENCES grammar_concepts(id) ON DELETE CASCADE,
    prerequisite_concept_id BIGINT NOT NULL REFERENCES grammar_concepts(id) ON DELETE CASCADE,
    UNIQUE (concept_id, prerequisite_concept_id),
    CHECK (concept_id <> prerequisite_concept_id)
);

