CREATE TABLE assessment_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_id BIGINT NOT NULL REFERENCES grammar_concepts(id) ON DELETE CASCADE,
    prompt VARCHAR(500) NOT NULL,
    options_json JSONB NOT NULL,
    correct_answer VARCHAR(300) NOT NULL,
    order_index INTEGER NOT NULL,
    UNIQUE (concept_id, order_index)
);

CREATE TABLE assessment_sessions (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    correct_count INTEGER,
    question_count INTEGER,
    estimated_level VARCHAR(2),
    confidence DOUBLE PRECISION,
    recommended_concept_code VARCHAR(80)
);

CREATE TABLE assessment_session_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES assessment_sessions(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES assessment_questions(id),
    order_index INTEGER NOT NULL,
    UNIQUE (session_id, question_id),
    UNIQUE (session_id, order_index)
);

CREATE TABLE assessment_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL,
    question_id BIGINT NOT NULL,
    selected_answer VARCHAR(300) NOT NULL,
    is_correct BOOLEAN NOT NULL,
    answered_at TIMESTAMPTZ NOT NULL,
    UNIQUE (session_id, question_id),
    FOREIGN KEY (session_id, question_id)
        REFERENCES assessment_session_questions(session_id, question_id) ON DELETE CASCADE
);

